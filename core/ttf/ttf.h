// Lumora CPU TrueType reader (scope AA). Pure CPU, deterministic, no I/O, no threads, no floating point at all.
// The interface in this header is fixed; the contributor implements core/ttf/ttf.cpp only (plus tests and docs).
// Results must be bit-identical on Linux, Windows and Android: integer arithmetic only (64-bit where needed), no libm, no floats,
// no heap allocation, no recursion, no static mutable state, no pointer values in any decision except the Overlap check.
// Purpose: read untrusted TrueType font bytes (glyf outlines, cmap format 4, hmtx) and produce glyph outlines as core/outline
// commands in raster 24.8 fixed point, ready for core/vecdraw. Hinting is ignored. Evidence label: software (CPU) only.
// Test fonts are generated by the tests from code (hand-built bytes); no third-party font file is ever committed.
#pragma once
#include <cstddef>
#include <cstdint>

#include "outline.h"

namespace lumora::ttf {

constexpr std::size_t kMaxFontBytes = std::size_t{1} << 26;  // 64 MiB
constexpr std::uint32_t kMaxTables = 64;
constexpr std::uint32_t kMaxGlyphPoints = 340;      // points of one glyph after composites are expanded
constexpr std::uint32_t kMaxComponents = 16;        // components of one composite glyph
constexpr std::uint32_t kMaxGlyphCommands = 1020;   // = kMaxGlyphPoints + 2 * kMaxGlyphPoints: the bound for commands (see below)
constexpr std::int32_t kMaxSizeFx = 1 << 22;        // em size in 24.8 pixels (16384 pixels)
constexpr std::int32_t kMaxOriginFx = 1 << 23;      // |origin| in 24.8 pixels

enum class Status : std::uint8_t {
  Ok = 0,
  NullBuffer,      // a required pointer is null (all pointers are always required)
  BadFont,         // structure wrong: tag, directory, table bounds or lengths, head magic, unitsPerEm, loca/hmtx too short, ...
  MissingTable,    // one of head, maxp, loca, glyf, cmap, hhea, hmtx is absent
  Unsupported,     // valid but outside the subset: sfnt tag, maxp version, cmap without a usable format 4 subtable, glyph features
  BadSize,         // em size or origin out of range
  BadGlyph,        // glyph index at or above numGlyphs, or glyph data outside its table or inconsistent
  BadCmap,         // a cmap lookup reads outside the subtable
  TooComplex,      // more than kMaxGlyphPoints points or kMaxComponents components
  OutOfRange,      // a scaled coordinate beyond +/- raster::kMaxCoord (2^24) in magnitude
  BufferTooSmall,  // out_capacity < kMaxGlyphCommands (data independent)
  Overlap          // touched byte ranges intersect (modular address rule as in core/composite)
};
// Lower-case spaced names ("ok", "null buffer", "bad font", "missing table", "unsupported", "bad size", "bad glyph", "bad cmap",
// "too complex", "out of range", "buffer too small", "overlap"), "unknown" otherwise.
const char* status_text(Status s);

// The parsed view of a font. It only points into the caller's bytes (which must outlive it and stay unchanged); every offset is
// relative to data. Filled by parse_font only; its fields are not a stable input format.
struct Font {
  const std::uint8_t* data;
  std::size_t size;
  std::uint32_t units_per_em;
  std::uint32_t num_glyphs;
  std::uint32_t num_hmetrics;
  bool loca_long;
  std::size_t loca_off, loca_len;
  std::size_t glyf_off, glyf_len;
  std::size_t hmtx_off, hmtx_len;
  std::size_t cmap_off, cmap_len;  // the chosen format 4 subtable
};

// Parses and validates the structure (not every glyph). All integers are big endian. Rules:
//  * size in 12 .. kMaxFontBytes else BadFont; sfnt tag 0x00010000 or 'true' (0x74727565), anything else Unsupported (including
//    'OTTO' and 'ttcf').
//  * numTables in 1 .. kMaxTables else BadFont; each 16-byte record (tag, checksum ignored, offset, length) must lie inside the file
//    (64-bit arithmetic) and a tag may appear once (BadFont); the directory itself must fit.
//  * Required tables head, maxp, loca, glyf, cmap, hhea, hmtx, else MissingTable (reported for the first missing in this order).
//  * head: length >= 54, magic 0x5F0F3CF5 at 12, unitsPerEm at 18 in 16 .. 16384, indexToLocFormat at 50 in {0, 1}; else BadFont.
//  * maxp: length >= 6, version 0x00010000 at 0 else Unsupported, numGlyphs at 4 in 1 .. 65535 (u16 so 0 is the only bad value).
//  * loca: length >= (numGlyphs + 1) * (2 for the short and 4 for the long format) else BadFont.
//  * hhea: length >= 36, numberOfHMetrics at 34 in 1 .. numGlyphs; hmtx length >= 4 * numberOfHMetrics + 2 * (numGlyphs -
//    numberOfHMetrics); else BadFont.
//  * cmap: length >= 4, version 0 at 0, numTables at 2 (<= 64 else BadFont); each 8-byte record (platform, encoding, offset from
//    the table start) must have the 4 bytes at its offset inside the table. Choose the first record with platform 3 encoding 1, else
//    the first with platform 0 encoding 3; none is Unsupported; its subtable must have format 4 else Unsupported; the format 4
//    length field is ignored, the subtable extends to the end of the cmap table; its header and arrays must fit: segCountX2 at 6 is
//    even and nonzero, 16 + 4 * segCountX2 bytes (header, endCode, reservedPad, startCode, idDelta, idRangeOffset) fit, else BadFont.
// Checks in this order: NullBuffer (data, out), the size rule, the sfnt tag, the directory, the tables in the order above.
// On any error *out is not written.
Status parse_font(const std::uint8_t* data, std::size_t size, Font* out);

// BMP only: code points above 0xFFFF give glyph 0 (Ok). Standard format 4 lookup: the first segment (in table order) whose endCode
// is >= the code point; if its startCode is greater, glyph 0. idRangeOffset 0: (cp + idDelta) mod 65536. Otherwise the glyph id word
// is read at (position of that idRangeOffset entry + idRangeOffset + 2 * (cp - startCode)); a read outside the subtable is BadCmap;
// a stored value of 0 stays 0, else it is (value + idDelta) mod 65536. A final glyph id at or above numGlyphs is 0 (Ok). Segments
// are not required to be sorted or non overlapping; the scan is linear and bounded by segCount. Nothing is written on error.
Status glyph_index(const Font& font, std::uint32_t code_point, std::uint32_t* glyph_out);

// Advance width in font units of a glyph (< numGlyphs else BadGlyph): hmtx entry glyph if glyph < numberOfHMetrics, else the last
// entry's advance.
Status glyph_advance(const Font& font, std::uint32_t glyph, std::uint32_t* advance_out);

// Decisions on the open reading questions (binding, they refine the rules above and above all fix the order of checks):
//  * parse_font: all seven presence checks (MissingTable, in the order head, maxp, loca, glyf, cmap, hhea, hmtx) run first; the content
//    checks then run in the order head, maxp, loca, hhea together with the hmtx length, cmap. glyf has no content check.
//  * glyph_index and glyph_advance: NullBuffer when font.data or the output pointer is null, checked first; there is no Overlap check
//    for them; then the rules above. Nothing is written on an error.
//  * glyph_outline Overlap: three pairs are checked: out against out_count, out against the font bytes (font.data .. +size), and
//    out_count (4 bytes) against the font bytes. The extent of out is always kMaxGlyphCommands * sizeof(Command), whatever
//    out_capacity is (it is at least kMaxGlyphCommands once BufferTooSmall passed).
//  * loca per glyph: only the entries g and g + 1 are read; loca[g] <= loca[g + 1] <= glyf_len (in bytes, after doubling for the short
//    format) else BadGlyph, also for an empty range. A non-empty range shorter than the 10 byte header is BadGlyph.
//  * Composite order of errors: for each component in turn: read flags, glyph and the two arguments (BadGlyph when they do not fit);
//    check the flags (Unsupported); look up the component glyph (BadGlyph when >= numGlyphs or its data is bad, Unsupported when it
//    is a composite); read its point count from its endPtsOfContours; add it to the total and fail TooComplex at once when the total
//    exceeds kMaxGlyphPoints, before reading that component's flags and coordinates. Only after a component is fully processed does
//    its 0x0020 flag matter: when it is the kMaxComponents-th component, 0x0020 gives TooComplex without reading a 17th.
//  * Flag 0x0100 counts on the last component only (the one without 0x0020); on earlier components it is ignored. The instruction
//    length (u16) and the instructions must fit in the glyph data, else BadGlyph.
//  * Contour walk: first point on-curve: start there and walk points 1 .. n - 1. Else last point on-curve: start there and walk points
//    0 .. n - 2. Else start at the exact midpoint (doubled units) of the first and last point and walk points 0 .. n - 1.
//  * Coordinates accumulate as signed 32-bit values in doubled font units, with no 16-bit wraparound (the sums of at most 340 points
//    of 16-bit deltas, plus component offsets, fit); offsets are signed 16-bit words or signed bytes.

// Glyph outline as commands. Scaling: a coordinate d in DOUBLED font units (2 * the font unit value, so the implied midpoints
// below stay exact) becomes fx = round(d * size_fx / (2 * units_per_em)), nearest, ties away from zero, with exact 64-bit
// integer arithmetic. x_fx = origin_x + fx(d_x) and y_fx = origin_y - fx(d_y) (font y grows up, raster y grows down). Every
// result must be within +/- 2^24 (raster::kMaxCoord) else OutOfRange.
//
// Glyph data (loca[g] .. loca[g + 1], offsets doubled for the short format, loca must be non decreasing and inside glyf else
// BadGlyph); an empty range is an empty glyph: Ok with count 0. Otherwise numberOfContours (i16) at 0 and the bounding box (ignored)
// follow; 10 bytes of header must fit.
//  * Simple glyph (numberOfContours >= 0; 0 contours is Ok with count 0): endPtsOfContours strictly increasing else BadGlyph; the point
//    count is the last end + 1 (> kMaxGlyphPoints is TooComplex); instructionLength is skipped (it must fit); flags with the
//    repeat bit expand to exactly the point count (running past it is BadGlyph); x and y coordinates by the standard short/same
//    flags; every read is bounds checked against the glyph data (else BadGlyph); the data after the y coordinates is ignored.
//    Flags used: bit 0 on-curve, bit 1 x short, bit 2 y short, bit 3 repeat, bit 4 x same/positive, bit 5 y same/positive; others ignored.
//  * Composite glyph (numberOfContours < 0): components in order, at most kMaxComponents (more is TooComplex), each flags u16, glyph u16,
//    then two arguments (words if flag 0x0001, else bytes). Flag 0x0002 (arguments are xy offsets) is required (else Unsupported).
//    Any of the scale flags 0x0008, 0x0040, 0x0080 is Unsupported; flag 0x0020 means more components follow; flag 0x0100 means
//    instructions follow after the last component (skipped, must fit); other flag bits are ignored. A component glyph must be a
//    SIMPLE glyph (a composite component is Unsupported: no recursion), glyph < numGlyphs (else BadGlyph). The component's points are
//    moved by the (signed) offsets in font units, contours keep their order, and the total point count over all components must be
//    <= kMaxGlyphPoints else TooComplex.
//  * Contour to commands (applied per contour with n points; a contour with n < 2 points emits nothing): all coordinates are doubled
//    font units and on-curve flags are bit 0. Start point S: the first point if it is on-curve; else the last point if it is on-curve
//    (and then the last point is skipped in the walk); else the exact midpoint of the first and the last point (and the walk starts at
//    the first point, ending after the last). Emit Move to S. Walk the remaining points in order with one pending control point:
//    on-curve point p: with a pending control c emit Quad(c, p) and clear it, else emit Line(p); off-curve point p: with a pending
//    control c emit Quad(c, m) where m is the exact midpoint of c and p, then p becomes the pending control; without one, p becomes the
//    pending control. After the walk, with a pending control c emit Quad(c, S). Then emit Close. Commands use outline::Command with
//    Quad: a = control, b = end; Line and Move: a; unused fields zero. A degenerate command (a repeated point) is kept as is; the outline
//    builder collapses duplicates.
// Bound: commands <= points + 2 * contours <= 3 * kMaxGlyphPoints = kMaxGlyphCommands (each point yields at most one Line or Quad, each
// implied start point and each contour one Move and one Close). The contributor proves it in docs/ttf.md.
//
// Checks in this order: NullBuffer (font.data, out, out_count; all pointers are always required), BadSize (size_fx not in
// 1 .. kMaxSizeFx, or an origin beyond +/- kMaxOriginFx), BadGlyph (glyph >= numGlyphs), BufferTooSmall (out_capacity <
// kMaxGlyphCommands), Overlap (out over kMaxGlyphCommands commands, against out_count and against the font bytes font.data .. +size),
// then the data dependent glyph errors in the order the glyph is read (BadGlyph, TooComplex, Unsupported, OutOfRange). Nothing is
// written to out or out_count on any error (the contributor stages the commands in local storage and copies at the end).
Status glyph_outline(const Font& font, std::uint32_t glyph, std::int32_t size_fx, std::int32_t origin_x_fx, std::int32_t origin_y_fx,
                     outline::Command* out, std::uint32_t out_capacity, std::uint32_t* out_count);

// FNV-1a 64 over 32-bit little-endian words: per command the op, then a.x, a.y, b.x, b.y, c.x, c.y (all as uint32 two's complement
// words). Null or zero count hashes zero bytes.
std::uint64_t digest_commands(const outline::Command* cmds, std::size_t count);

}  // namespace lumora::ttf
