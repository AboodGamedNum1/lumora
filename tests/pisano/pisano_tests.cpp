constexpr u64 kSent = 0x5A5A5A5A5A5A5A5Aull;
constexpr u64 kInit = 0xcbf29ce484222325ull;
u64 fnv(u64 h, u64 w) { return (h ^ w) * 0x100000001b3ull; }

struct Res {
  PisanoResult r;
  u64 v;
  bool guards;
};
Res call(u32 m) {
  u64 cell[5] = {kSent, kSent, kSent, kSent, kSent};
  Res o;
  o.r = pisano_period(m, cell + 2);
  o.v = cell[2];
  o.guards = cell[0] == kSent && cell[1] == kSent && cell[3] == kSent && cell[4] == kSent;
  return o;
}
u64 pi_of(u32 m, bool& ok) {
  const Res r = call(m);
  ok = r.r == PisanoResult::Ok && r.guards;
  return r.v;
}

// brute force: walk until the pair (0, 1 % m) returns
u64 walk(u32 m) {
  const u64 mm = m;
  u64 a = 0, b = 1u % mm, n = 0;
  for (;;) {
    const u64 t = (a + b) % mm;
    a = b;
    b = t;
    ++n;
    if (a == 0u && b == 1u % mm) return n;
  }
}

// certificate by 2 x 2 matrices
struct Mat {
  u64 a, b, c, d;
};
Mat mul(const Mat& x, const Mat& y, u64 m) {
  return Mat{((x.a * y.a) % m + (x.b * y.c) % m) % m, ((x.a * y.b) % m + (x.b * y.d) % m) % m, ((x.c * y.a) % m + (x.d * y.c) % m) % m,
             ((x.c * y.b) % m + (x.d * y.d) % m) % m};
}
bool is_id(u64 n, u64 m) {
  Mat r{1u % m, 0u, 0u, 1u % m};
  Mat b{1u % m, 1u % m, 1u % m, 0u};
  while (n != 0u) {
    if ((n & 1u) != 0u) r = mul(r, b, m);
    b = mul(b, b, m);
    n >>= 1;
  }
  return r.a == 1u % m && r.b == 0u && r.c == 0u && r.d == 1u % m;
}
bool certificate(u32 m, u64 n) {
  if (n == 0u || !is_id(n, m)) return false;
  u64 rem = n;
  for (u64 q = 2; q * q <= rem; q += (q == 2u) ? 1u : 2u) {
    if (rem % q != 0u) continue;
    while (rem % q == 0u) rem /= q;
    if (m > 1u && is_id(n / q, m)) return false;
  }
  if (rem > 1u && m > 1u && is_id(n / rem, m)) return false;
  return true;
}

void sweep(u32 k) {
  const u32 lo = (k == 0u) ? 1u : k * kChunkSize;
  const u32 hi = (k == 7u) ? (1u << 20) : (k + 1u) * kChunkSize - 1u;
  u64 h = kInit;
  u32 bad = 0;
  for (u32 m = lo; m <= hi; ++m) {
    bool ok = false;
    const u64 v = pi_of(m, ok);
    if (!ok || v < 1u || v > 6u * static_cast<u64>(m)) ++bad;
    h = fnv(fnv(h, m), v);
  }
  CHECK(bad == 0u);
  CHECK(h == kChunkDigest[k]);
}

void certify(u32 lo, u32 hi) {
  u32 bad = 0;
  for (u32 m = lo; m <= hi; ++m) {
    bool ok = false;
    const u64 v = pi_of(m, ok);
    if (!ok || !certificate(m, v)) ++bad;
  }
  CHECK(bad == 0u);
}

