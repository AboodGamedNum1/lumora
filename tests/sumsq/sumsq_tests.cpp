// values, and from digests and tables made by tools/sumsq_ref.py (standard library only; it factors by its own trial division, enumerates ALL divisors and takes
// r2 = 4 (d1 - d3), r4 = 8 * the sum of the divisors not divisible by 4; its large values also pass the x-loop in Python). The two-square theorem and Jacobi's four-square
