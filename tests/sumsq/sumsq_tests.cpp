// r2(n) and r4(n) are the numbers of integer solutions of x^2 + y^2 = n and x^2 + y^2 + z^2 + w^2 = n. Expected values come from the header's table, from in-test brute force
// (a histogram of x^2 + y^2 over all x, y; the direct 4-variable loop for n <= 60; the convolution r4(n) = sum_k r2(k) r2(n - k) of that histogram), from in-test sieves that do not
