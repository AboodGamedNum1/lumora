//   exhaustive vs the digests: every n = 0..2^20 (8 chunk cases of 2^17 values; chunk 0 holds n = 0, the last holds 2^20);
//   identities: every n = 1..2^19 (r2(2n) = r2(n), r4(2n) = 3 r4(n) or r4(n)), 40000 sampled coprime pairs (multiplicativity);
