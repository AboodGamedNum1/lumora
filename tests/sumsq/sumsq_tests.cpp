constexpr u64 kGuard = 0xA5A5A5A5A5A5A5A5ull;
constexpr u64 kSentinel = 0xDEADBEEFDEADBEEFull;

// Calls the function with the result cell between guards; the guards must survive. fn2 selects count_two_squares.
SqResult call(bool fn2, u32 n, u64* cell, bool* guards_ok) {
  u64 box[3] = {kGuard, *cell, kGuard};
  const SqResult r = fn2 ? count_two_squares(n, &box[1]) : count_four_squares(n, &box[1]);
  *guards_ok = (box[0] == kGuard) && (box[2] == kGuard);
  *cell = box[1];
  return r;
}

u64 r2of(u32 n) {
  u64 v = kSentinel;
  bool g = true;
  const SqResult r = call(true, n, &v, &g);
  const bool ok = (r == SqResult::Ok) && g;
  return ok ? v : kSentinel;
}
u64 r4of(u32 n) {
  u64 v = kSentinel;
  bool g = true;
  const SqResult r = call(false, n, &v, &g);
  const bool ok = (r == SqResult::Ok) && g;
  return ok ? v : kSentinel;
}

u64 fnv_step(u64 h, u64 w) { return (h ^ w) * 0x100000001b3ull; }

u64 next_rand(u64* s) {
  u64 x = *s;
  x ^= x << 13;
  x ^= x >> 7;
  x ^= x << 17;
  *s = x;
  return x;
}

constexpr u32 kTop = 1u << 21;

// r2 by the histogram of x^2 + y^2 over all integer x, y.
const std::vector<std::uint16_t>& hist() {
  static const std::vector<std::uint16_t> h = [] {
    std::vector<std::uint16_t> v(kTop + 1u, 0u);
    for (i64 x = -1449; x <= 1449; ++x)
      for (i64 y = -1449; y <= 1449; ++y) {
        const i64 s = x * x + y * y;
        if (s <= static_cast<i64>(kTop)) ++v[static_cast<std::size_t>(s)];
      }
    return v;
  }();
  return h;
}
// sigma sieve (sum of all divisors) and the d1 - d3 sieve (divisors 1 mod 4 minus divisors 3 mod 4), n = 1..kTop.
const std::vector<u32>& sigma_sieve() {
  static const std::vector<u32> s = [] {
    std::vector<u32> v(kTop + 1u, 0u);
    for (u32 d = 1; d <= kTop; ++d)
      for (u32 m = d; m <= kTop; m += d) v[m] += d;
    return v;
  }();
  return s;
}
