u64 digest_subsets(u32 n, bool loops, bool add_all_loops = false) {
  std::vector<std::pair<u32, u32>> pairs;
  for (u32 u = 0; u < n; ++u) {
    for (u32 v = 0; v < n; ++v) {
      if (loops || u != v) pairs.push_back({u, v});
    }
  }
  u64 h = kFnvOff;
  const u32 k = static_cast<u32>(pairs.size());
  for (u32 mask = 0; mask < (1u << k); ++mask) {
    Graph g;
    g.nodes = n;
    for (u32 i = 0; i < k; ++i) {
      if (((mask >> i) & 1u) != 0u) g.add(pairs[i].first, pairs[i].second);
    }
    if (add_all_loops) {
      for (u32 v = 0; v < n; ++v) g.add(v, v);
    }
    const Run r = run(g);
    h = fold_run(h, r);
  }
  return h;
}

// Every kSampleStride-th edge set of the 2^25 looped graphs on 5 nodes, as in the reference.
u64 digest_strided(u32* cases) {
  const u32 n = 5;
  u64 h = kFnvOff;
  *cases = 0;
  for (u64 mask = 0; mask < (1ull << 25); mask += 331ull) {
    Graph g;
    g.nodes = n;
    for (u32 i = 0; i < 25u; ++i) {
      if (((mask >> i) & 1ull) != 0ull) g.add(i / n, i % n);
    }
    h = fold_run(h, run(g));
    ++*cases;
  }
  return h;
}

u64 digest_sequences(u32 n, u32 maxlen, u32* cases) {
  const u32 np = n * n;
  u64 h = kFnvOff;
  *cases = 0;
  std::vector<u32> seq;
  // All sequences of each length 0 .. maxlen over the n * n ordered pairs, in lexicographic order per length (as the reference).
  for (u32 len = 0; len <= maxlen; ++len) {
    u64 total = 1;
    for (u32 i = 0; i < len; ++i) total *= np;
    for (u64 idx = 0; idx < total; ++idx) {
      Graph g;
      g.nodes = n;
      u64 x = idx;
      std::vector<u32> digits(len);
      for (u32 i = len; i > 0; --i) {
        digits[i - 1u] = static_cast<u32>(x % np);
        x /= np;
      }
      for (u32 i = 0; i < len; ++i) g.add(digits[i] / n, digits[i] % n);
      h = fold_run(h, run(g));
      ++*cases;
    }
  }
  return h;
}
