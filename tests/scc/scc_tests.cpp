u64 fold_word(u64 h, u32 v) {
  for (int i = 0; i < 4; ++i) {
    h ^= (v & 0xFFu);
    v >>= 8;
    h *= 0x100000001B3ull;
  }
  return h;
}

struct Graph {
  u32 nodes = 0;
  std::vector<u32> eu, ev;
  u32 edges() const { return static_cast<u32>(eu.size()); }
  void add(u32 u, u32 v) {
    eu.push_back(u);
    ev.push_back(v);
  }
};

struct Run {
  SccResult res;
  u32 count;
  std::vector<u32> comp;
};

// Exact-size scratch (filled with `fill`) and an exact-size sentinel-filled comp array.
Run run(const Graph& g, u32 fill = kGarbage) {
  const u32 n = g.nodes;
  const u32 m = g.edges();
  std::vector<u32> scratch(6ull * n + m + 1ull, fill);
  Run r;
  r.comp.assign(n, kSentinel);
  r.count = kSentinel;
  r.res = scc_run(n, m, g.eu.data(), g.ev.data(), scratch.data(), static_cast<u32>(scratch.size()), r.comp.data(), &r.count);
  return r;
}

u64 fold_run(u64 h, const Run& r) {
  h = fold_word(h, r.count);
  for (u32 c : r.comp) h = fold_word(h, c);
  return h;
}

// Canonical numbering check: numbers appear in order of first occurrence, and every number is below count.
bool canonical(const Run& r) {
  u32 next = 0;
  for (u32 c : r.comp) {
    if (c > next) return false;
    if (c == next) ++next;
  }
  return next == r.count;
}

struct Lcg {
  u64 s;
  u32 next() {
    s = s * 6364136223846793005ull + 1442695040888963407ull;
    return static_cast<u32>(s >> 33);
  }
  u32 rnd(u32 k) { return next() % k; }
};

std::vector<u32> shuffled_perm(u32 n, Lcg& r) {
  std::vector<u32> p(n);
  for (u32 i = 0; i < n; ++i) p[i] = i;
  for (u32 i = n - 1u; i > 0; --i) {
    const u32 j = r.rnd(i + 1u);
    const u32 t = p[i];
    p[i] = p[j];
    p[j] = t;
  }
  return p;
}

