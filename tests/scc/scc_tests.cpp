Graph big_graph(u32 pid) {
  Lcg r = {3000ull + pid};
  const u32 N = 65536u, M = 262144u;
  Graph g;
  g.nodes = N;
  if (pid == 0) {
    for (u32 k = 0; k < 4; ++k) {
      for (u32 i = 0; i < N; ++i) g.add(i, (i + 1u) % N);
    }
  } else if (pid == 1) {
    const std::vector<u32> p = shuffled_perm(N, r);
    for (u32 i = 0; i < N; ++i) g.add(p[i], p[(i + 1u) % N]);
    for (u32 k = 0; k < M - N; ++k) {
      const u32 a = r.rnd(N);
      const u32 b = r.rnd(N);
      g.add(p[a], p[b]);
    }
  } else if (pid == 2) {
    for (u32 i = 0; i + 1u < N; ++i) g.add(i, i + 1u);
  } else if (pid == 3) {
    for (u32 i = 0; i + 1u < N; ++i) g.add(i + 1u, i);
  } else if (pid == 4) {
    for (u32 i = 0; i + 1u < N; ++i) g.add(i, i + 1u);
    g.add(N - 1u, 0);
  } else if (pid == 5) {
    for (u32 u = 0; u < 512u; ++u) {
      for (u32 v = 0; v < 512u; ++v) g.add(u, v);
    }
  } else if (pid == 6) {
    for (u32 c = 0; c < 21845u; ++c) {
      const u32 a = 3u * c;
      g.add(a, a + 1u);
      g.add(a + 1u, a + 2u);
      g.add(a + 2u, a);
      if (c + 1u < 21845u) g.add(a, a + 3u);
    }
  } else if (pid == 7) {
    for (u32 k = 0; k < M; ++k) {
      const u32 a = r.rnd(N - 1u);
      const u32 b = a + 1u + r.rnd(N - 1u - a);
      g.add(a, b);
    }
  } else if (pid == 8) {
    // no edges
  } else if (pid == 9) {
    for (u32 i = 0; i < N; ++i) g.add(i, i);
  } else if (pid == 10) {
    const std::vector<u32> p = shuffled_perm(N, r);
    const u32 h = N / 2u;
    for (u32 i = 0; i < h; ++i) g.add(p[i], p[(i + 1u) % h]);
    for (u32 i = 0; i < h; ++i) g.add(p[h + i], p[h + (i + 1u) % h]);
    g.add(p[0], p[h]);
    for (u32 k = 0; k < M - N - 1u; ++k) {
      const u32 side = r.rnd(2);
      const u32 a = r.rnd(h);
      const u32 b = r.rnd(h);
      g.add(p[side * h + a], p[side * h + b]);
    }
  } else if (pid == 11) {
    for (u32 k = 0; k < M; ++k) {
      const u32 a = r.rnd(N);
      const u32 b = r.rnd(N);
      g.add(a, b);
    }
  } else if (pid == 13) {
    for (u32 k = 0; k < M; ++k) {
      const u32 l = r.rnd(255);
      const u32 a = l * 256u + r.rnd(256);
      const u32 b = (l + 1u) * 256u + r.rnd(256);
      g.add(a, b);
    }
  } else if (pid == 12) {
    for (u32 c = 0; c < 4u; ++c) {
      for (u32 a = 0; a < 256u; ++a) {
        for (u32 b = 0; b < 256u; ++b) g.add(c + 4u * a, c + 4u * b);
      }
    }
  }
  return g;
}

