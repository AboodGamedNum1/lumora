// The in-test one-subtraction walk: the code and the index the header defines for p / q.
struct Walk {
  CwResult r;
  u64 index;
};
Walk walk_single(u32 p, u32 q) {
  if (p == 0u || q == 0u) return {CwResult::BadArgument, 0u};
  if (gcd64(p, q) != 1u) return {CwResult::NotCoprime, 0u};
  u64 x = p, y = q;
  u64 steps = 0u;
  u64 bits = 0u;
  while (x != 1u || y != 1u) {
    u64 bit = 0u;
    if (x > y) {
      x -= y;
      bit = 1u;
    } else {
      y -= x;
    }
    if (steps < 64u) bits |= bit << steps;
    ++steps;
  }
  if (steps > 63u) return {CwResult::TooLarge, 0u};
  return {CwResult::Ok, (u64{1} << steps) | bits};
}

