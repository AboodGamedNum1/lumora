constexpr u64 kGuard = 0xA5A5A5A5A5A5A5A5ull;
constexpr u64 kSentinel = 0xDEADBEEFDEADBEEFull;
constexpr i32 kMuSentinel = 12345;  // mu is -1, 0 or 1
constexpr u32 kTop = (1u << 24) + 1u;

// mu(n) through the public call, the cell between guards; kMuSentinel if the call fails or a guard is hit.
i32 mu_of(u32 n) {
  u64 box[3] = {kGuard, 0u, kGuard};
  i32 cell[3] = {7, kMuSentinel, 7};
  const SfResult r = mobius(n, &cell[1]);
  box[1] = 0u;
  const bool guards = (cell[0] == 7) && (cell[2] == 7) && (box[0] == kGuard) && (box[2] == kGuard);
  const bool ok = (r == SfResult::Ok) && guards;
  return ok ? cell[1] : kMuSentinel;
}
u64 q_of(u32 n) {
  u64 box[3] = {kGuard, kSentinel, kGuard};
  const SfResult r = squarefree_count(n, &box[1]);
  const bool guards = (box[0] == kGuard) && (box[2] == kGuard);
  const bool ok = (r == SfResult::Ok) && guards;
  return ok ? box[1] : kSentinel;
}

u64 fnv_step(u64 h, u64 w) { return (h ^ w) * 0x100000001b3ull; }
u64 next_rand(u64* s) {
  u64 x = *s;
  x ^= x << 13;
  x ^= x >> 7;
  x ^= x << 17;
  *s = x;
  return x;
}

// Definitional scan: flag[k] = 1 when no square above 1 divides k (k >= 1); prefix[k] = the number of flagged k' <= k.
const std::vector<u32>& prefix() {
  static const std::vector<u32> p = [] {
    std::vector<std::uint8_t> flag(kTop + 1u, 1u);
    flag[0] = 0u;
    for (u32 d = 2; d * d <= kTop; ++d)
      for (u32 m = d * d; m <= kTop; m += d * d) flag[m] = 0u;
    std::vector<u32> v(kTop + 1u, 0u);
    for (u32 k = 1; k <= kTop; ++k) v[k] = v[k - 1u] + flag[k];
    return v;
  }();
  return p;
}
// Linear sieve for mu, n = 1..2^22.
const std::vector<std::int8_t>& mu_sieve() {
  static const std::vector<std::int8_t> m = [] {
    constexpr u32 N = 1u << 22;
    std::vector<std::int8_t> mu(N + 1u, 0);
    std::vector<bool> comp(N + 1u, false);
    std::vector<u32> primes;
    mu[1] = 1;
    for (u32 i = 2; i <= N; ++i) {
      if (!comp[i]) {
        primes.push_back(i);
        mu[i] = -1;
      }
      for (std::size_t j = 0; j < primes.size(); ++j) {
        const u64 ip = static_cast<u64>(i) * primes[j];
        if (ip > N) break;
        comp[static_cast<std::size_t>(ip)] = true;
        if (i % primes[j] == 0u) {
          mu[static_cast<std::size_t>(ip)] = 0;
          break;
        }
        mu[static_cast<std::size_t>(ip)] = static_cast<std::int8_t>(-mu[i]);
      }
    }
    return mu;
  }();
  return m;
}

// The identity route, no mu: Q(n) = n - the sum over m >= 2 of Q(floor(n / m^2)), memoised over the flag table.
u64 q_ident(u64 n, std::map<u64, u64>* memo) {
  if (n <= kTop) return prefix()[static_cast<std::size_t>(n)];
  const auto it = memo->find(n);
  if (it != memo->end()) return it->second;
  u64 s = 0;
  for (u64 m = 2; m * m <= n; ++m) s += q_ident(n / (m * m), memo);
  const u64 r = n - s;
  (*memo)[n] = r;
  return r;
}

void mu_sieve_chunk(u32 k) {
  const u32 lo = (k == 0u) ? 1u : k * 524288u;
  const u32 hi = (k + 1u) * 524288u + ((k == 7u) ? 1u : 0u);
  const std::vector<std::int8_t>& s = mu_sieve();
  u64 bad = 0;
  u32 first = 0;
  for (u32 n = lo; n < hi; ++n)
    if (mu_of(n) != s[n]) {
      if (bad == 0) first = n;
      ++bad;
    }
  INFO("first bad n = " << first);
  CHECK(bad == 0u);
}

void mu_digest_chunk(u32 k) {
  const u32 lo = (k == 0u) ? 1u : k * 131072u;
  const u32 hi = k * 131072u + 131072u + ((k == 7u) ? 1u : 0u);
  u64 h = 0xcbf29ce484222325ull;
  for (u32 n = lo; n < hi; ++n) {
    h = fnv_step(h, n);
    h = fnv_step(h, static_cast<u64>(mu_of(n) + 1));
  }
  CHECK(h == kMuDigest[k]);
}

void count_chunk(u32 lo, u32 hi) {  // n in [lo, hi)
  u64 bad = 0;
  u32 first = 0;
  for (u32 n = lo; n < hi; ++n)
    if (q_of(n) != prefix()[n]) {
      if (bad == 0) first = n;
      ++bad;
    }
  INFO("first bad n = " << first);
  CHECK(bad == 0u);
}
