// Tests for core/squarefree. Evidence label: unit tests only.
// mu(n) is the Moebius function (0 when a square above 1 divides n, otherwise (-1)^k for k distinct primes, mu(1) = 1) and Q(n) counts the squarefree k with 1 <= k <= n.
// Expected values come from the header's table, from in-test definitional scans (a flag table of squarefree k made by marking multiples of d^2 for d >= 2, with prefix
// counts, to 2^24; a linear sieve for mu to 2^22; mu of special families straight from the definition), from an in-test copy of the identity route that uses no mu (every k
// is uniquely m^2 s with s squarefree, so Q(n) = n - the sum over m >= 2 of Q(floor(n / m^2)), memoised over the flag table), and from digests and tables made by
// tools/squarefree_ref.py (standard library only; it factors by its own trial division, computes Q by the definition, by the same identity route and by the mu-sum, and
// the three must agree on every entry). Extents, named in the test names and in docs/squarefree.md:
//   mobius vs the linear sieve: every n = 1..2^22 (8 chunk cases of 2^19); vs the digests: every n = 1..2^20 (8 chunk cases of 2^17; the last includes 2^20);
//   squarefree_count vs the flag table: every n = 0..2^17 (2 chunk cases); n = d^2 - 1, d^2, d^2 + 1 for every d = 1..4096; 4000 sampled n from 2^17 to 2^24;
//   identities: Q(n) - Q(n - 1) = mu(n)^2 for every n = 1..2^16; the sum over d of Q(floor(n / d^2)) = n for every n = 0..2^15; the sum of mu(d) over d | n is [n = 1]
//     for every n = 1..2^16; mu(ab) = mu(a) mu(b) on 20000 sampled coprime pairs;
//   every prime up to 65521 (mu(p) = -1, mu(p^2) = 0, mu(p q) = 1 for neighbouring primes) and the grid 2^a 3^b 5^c 7^d below 2^32 from the definition;
//   sampled large values: the lists below (1414 values of mu and 487 of Q, up to UINT32_MAX) against the tables; every large Q also against the in-test identity route.
