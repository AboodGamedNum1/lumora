    const u32 b = 1u + static_cast<u32>(next_rand(&s0) % 65535u);
    u32 x = a;
    u32 y = b;
    while (y != 0u) {
      const u32 t = x % y;
      x = y;
      y = t;
    }
    if (x != 1u) continue;
