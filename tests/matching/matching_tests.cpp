u64 digest_subsets(const std::vector<std::pair<u32, u32>>& sizes, u32* cases) {
  u64 h = kFnvOff;
  *cases = 0;
  for (const auto& lr : sizes) {
    const u32 l = lr.first, r = lr.second;
    const u32 k = l * r;
    for (u32 mask = 0; mask < (1u << k); ++mask) {
      Graph g;
      g.left = l;
      g.right = r;
      for (u32 i = 0; i < k; ++i) {
        if (((mask >> i) & 1u) != 0u) g.add(i / r, i % r);
      }
      h = fold_run(h, run(g));
      ++*cases;
    }
  }
  return h;
}

struct ListSpec {
  u32 l, r, maxlen;
};

// All ordered edge lists of each length 0 .. maxlen over the l * r pairs, lexicographic per length, for each spec in order (as the reference).
u64 digest_lists(const std::vector<ListSpec>& specs, u32* cases) {
  u64 h = kFnvOff;
  *cases = 0;
  for (const ListSpec& s : specs) {
    const u32 np = s.l * s.r;
    for (u32 len = 0; len <= s.maxlen; ++len) {
      u64 total = 1;
      for (u32 i = 0; i < len; ++i) total *= np;
      for (u64 idx = 0; idx < total; ++idx) {
        Graph g;
        g.left = s.l;
        g.right = s.r;
        u64 x = idx;
        std::vector<u32> digits(len);
        for (u32 i = len; i > 0; --i) {
          digits[i - 1u] = static_cast<u32>(x % np);
          x /= np;
        }
        for (u32 i = 0; i < len; ++i) g.add(digits[i] / s.r, digits[i] % s.r);
        h = fold_run(h, run(g));
        ++*cases;
      }
    }
  }
  return h;
}

u64 gd(u32 i) { return static_cast<u64>(kGroupDigest[2u * i + 1u]) << 32 | kGroupDigest[2u * i]; }
