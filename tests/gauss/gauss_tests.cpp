u64 fold_bytes(u64 h, u64 v, int nbytes) {
  for (int i = 0; i < nbytes; ++i) {
    h ^= (v & 0xFFu);
    v >>= 8;
    h *= kFnvPrime;
  }
  return h;
}

struct Lcg {
  u64 s;
  u64 rnd(u64 k) {
    s = s * 6364136223846793005ull + 1442695040888963407ull;
    return (s >> 33) % k;
  }
};

u32 mulm(u32 x, u32 y) { return static_cast<u32>((static_cast<u64>(x) * y) % kMod); }
u32 addm(u32 x, u32 y) { return static_cast<u32>((static_cast<u64>(x) + y) % kMod); }

std::size_t at(u32 i, u32 cols, u32 j) { return static_cast<std::size_t>(i) * cols + j; }

struct Sys {
  u32 rows = 0;
  u32 cols = 0;
  std::vector<u32> a;
  std::vector<u32> b;
};

// Expected result of a constructed system.
struct Expect {
  u32 rank = 0;
  u32 det = 0;
  SolveKind kind = SolveKind::Unique;
  std::vector<u32> x;
};

std::vector<u32> mat_vec(const Sys& s, const std::vector<u32>& x) {
  std::vector<u32> b(s.rows, 0u);
  for (u32 i = 0; i < s.rows; ++i) {
    u64 acc = 0;
    for (u32 j = 0; j < s.cols; ++j) acc = (acc + static_cast<u64>(s.a[at(i, s.cols, j)]) * x[j]) % kMod;
    b[i] = static_cast<u32>(acc);
  }
  return b;
}

Sys gen_random(u32 rows, u32 cols, u32 mode, u32 bmode, u64 seed) {
  Lcg g{seed};
  Sys s;
  s.rows = rows;
  s.cols = cols;
  const std::size_t cells = static_cast<std::size_t>(rows) * cols;
  s.a.assign(cells, 0u);
  if (mode == 0) {
    for (std::size_t i = 0; i < cells; ++i) s.a[i] = static_cast<u32>(g.rnd(kMod));
  } else if (mode == 1) {
    const u32 tab[5] = {0u, 1u, 2u, kMod - 2u, kMod - 1u};
    for (std::size_t i = 0; i < cells; ++i) s.a[i] = tab[g.rnd(5)];
  } else if (mode == 2) {
    for (std::size_t i = 0; i < cells; ++i) {
      if (g.rnd(5) == 0) {
        s.a[i] = static_cast<u32>(g.rnd(kMod));
      } else {
        s.a[i] = 0u;
      }
    }
  } else {
    const u32 k = 1u + static_cast<u32>(g.rnd(rows < cols ? rows : cols));
    std::vector<u32> xm(static_cast<std::size_t>(rows) * k);
    std::vector<u32> ym(static_cast<std::size_t>(k) * cols);
    for (std::size_t i = 0; i < xm.size(); ++i) xm[i] = static_cast<u32>(g.rnd(kMod));
    for (std::size_t i = 0; i < ym.size(); ++i) ym[i] = static_cast<u32>(g.rnd(kMod));
    for (u32 i = 0; i < rows; ++i) {
      for (u32 j = 0; j < cols; ++j) {
        u64 acc = 0;
        for (u32 t = 0; t < k; ++t) acc = (acc + static_cast<u64>(xm[at(i, k, t)]) * ym[at(t, cols, j)]) % kMod;
        s.a[at(i, cols, j)] = static_cast<u32>(acc);
      }
    }
  }
  if (bmode == 0) {
    std::vector<u32> x0(cols);
    for (u32 j = 0; j < cols; ++j) x0[j] = static_cast<u32>(g.rnd(kMod));
    s.b = mat_vec(s, x0);
  } else if (bmode == 1) {
    s.b.assign(rows, 0u);
    for (u32 i = 0; i < rows; ++i) s.b[i] = static_cast<u32>(g.rnd(kMod));
  } else {
    s.b.assign(rows, 0u);
  }
  return s;
}

// A = P * L * E * U with a known answer (see tools/gauss_ref.py).
Sys gen_constructed(u32 rows, u32 cols, u32 zero_den, u32 bmode, u32 perm_flag, u64 seed, Expect* ex) {
  Lcg g{seed};
  const u32 mn = rows < cols ? rows : cols;
  std::vector<u32> e(mn);
  for (u32 k = 0; k < mn; ++k) {
    if (zero_den > 0 && g.rnd(zero_den) == 0) {
      e[k] = 0u;
    } else {
      e[k] = 1u + static_cast<u32>(g.rnd(kMod - 1u));
    }
  }
  std::vector<u32> lm(static_cast<std::size_t>(rows) * rows, 0u);
  for (u32 i = 0; i < rows; ++i) {
    for (u32 k = 0; k < i; ++k) lm[at(i, rows, k)] = static_cast<u32>(g.rnd(kMod));
    lm[at(i, rows, i)] = 1u;
  }
  std::vector<u32> um(static_cast<std::size_t>(cols) * cols, 0u);
  for (u32 k = 0; k < cols; ++k) {
    um[at(k, cols, k)] = 1u;
    for (u32 j = k + 1u; j < cols; ++j) um[at(k, cols, j)] = static_cast<u32>(g.rnd(kMod));
  }
  std::vector<u32> tm(static_cast<std::size_t>(rows) * cols, 0u);
  for (u32 k = 0; k < mn; ++k) {
    for (u32 j = 0; j < cols; ++j) tm[at(k, cols, j)] = mulm(e[k], um[at(k, cols, j)]);
  }
  Sys s;
  s.rows = rows;
  s.cols = cols;
  s.a.assign(static_cast<std::size_t>(rows) * cols, 0u);
  for (u32 i = 0; i < rows; ++i) {
    const u32 kmax = (i < mn - 1u ? i : mn - 1u);
    for (u32 j = 0; j < cols; ++j) {
      u64 acc = 0;
      for (u32 k = 0; k <= kmax; ++k) acc = (acc + static_cast<u64>(lm[at(i, rows, k)]) * tm[at(k, cols, j)]) % kMod;
      s.a[at(i, cols, j)] = static_cast<u32>(acc);
    }
  }
  u32 rank = 0;
  for (u32 k = 0; k < mn; ++k) {
    if (e[k] != 0u) ++rank;
  }
  std::vector<u32> x0(cols);
  for (u32 j = 0; j < cols; ++j) {
    const u32 v = static_cast<u32>(g.rnd(kMod));
    x0[j] = (j < mn && e[j] != 0u) ? v : 0u;
  }
  s.b = mat_vec(s, x0);
  bool consistent = true;
  if (bmode == 1) {
    u32 t = 0;
    while (t < rows && (t < mn && e[t] != 0u)) ++t;
    for (u32 i = t; i < rows; ++i) s.b[i] = addm(s.b[i], lm[at(i, rows, t)]);
    consistent = false;
  }
  u32 sign_neg = 0;
  if (perm_flag != 0u) {
    std::vector<u32> perm(rows);
    for (u32 i = 0; i < rows; ++i) perm[i] = i;
    for (u32 i = rows; i-- > 1u;) {
      const u32 j = static_cast<u32>(g.rnd(static_cast<u64>(i) + 1u));
      std::swap(perm[i], perm[j]);
    }
    std::vector<u32> na(s.a.size());
    std::vector<u32> nb(rows);
    for (u32 i = 0; i < rows; ++i) {
      for (u32 j = 0; j < cols; ++j) na[at(i, cols, j)] = s.a[at(perm[i], cols, j)];
      nb[i] = s.b[perm[i]];
    }
    s.a = na;
    s.b = nb;
    std::vector<bool> seen(rows, false);
    for (u32 i = 0; i < rows; ++i) {
      if (!seen[i]) {
        u32 j = i;
        u32 len = 0;
        while (!seen[j]) {
          seen[j] = true;
          j = perm[j];
          ++len;
        }
        if (len % 2u == 0u) sign_neg ^= 1u;
      }
    }
  }
  ex->rank = rank;
  ex->det = 0u;
  if (rows == cols && rank == rows) {
    u32 prod = 1u;
    for (u32 k = 0; k < mn; ++k) prod = mulm(prod, e[k]);
    ex->det = (sign_neg != 0u) ? (kMod - prod) % kMod : prod;
  }
  if (!consistent) {
    ex->kind = SolveKind::Inconsistent;
    ex->x.clear();
  } else {
    ex->kind = (rank == cols) ? SolveKind::Unique : SolveKind::Many;
    ex->x = x0;
  }
  return s;
}

// ------------------------------------------------------------------ brute force (independent of the library)
u32 det_leibniz(const std::vector<u32>& m, u32 n) {
  if (n == 0) return 1u;
  std::vector<u32> p(n);
  for (u32 i = 0; i < n; ++i) p[i] = i;
  u64 total = 0;
  do {
    u32 inv = 0;
    for (u32 i = 0; i < n; ++i) {
      for (u32 j = i + 1u; j < n; ++j) {
        if (p[i] > p[j]) ++inv;
      }
    }
    u32 prod = 1u;
    for (u32 i = 0; i < n; ++i) prod = mulm(prod, m[at(i, n, p[i])]);
    total = (inv % 2u == 0u) ? (total + prod) % kMod : (total + kMod - prod) % kMod;
  } while (std::next_permutation(p.begin(), p.end()));
  return static_cast<u32>(total);
}

// Rank of the first use columns of the rows x stride matrix a: the largest k with a nonzero k x k minor.
u32 rank_minors(const std::vector<u32>& a, u32 rows, u32 stride, u32 use) {
  const u32 mn = rows < use ? rows : use;
  for (u32 k = mn; k >= 1u; --k) {
    for (u32 rs = 0; rs < (1u << rows); ++rs) {
      u32 rc = 0;
      for (u32 i = 0; i < rows; ++i) rc += (rs >> i) & 1u;
      if (rc != k) continue;
      for (u32 cs = 0; cs < (1u << use); ++cs) {
        u32 cc = 0;
        for (u32 j = 0; j < use; ++j) cc += (cs >> j) & 1u;
        if (cc != k) continue;
        std::vector<u32> sub;
        for (u32 i = 0; i < rows; ++i) {
          if (((rs >> i) & 1u) == 0u) continue;
          for (u32 j = 0; j < use; ++j) {
            if (((cs >> j) & 1u) != 0u) sub.push_back(a[at(i, stride, j)]);
          }
        }
        if (det_leibniz(sub, k) != 0u) return k;
      }
    }
  }
  return 0u;
}

struct SolveOut {
  GaussResult res = GaussResult::NullArgument;
  u32 rank = kSentinel;
  SolveKind kind = kKindSentinel;
  std::vector<u32> x;
  bool clean = false;
};

// Checks a solve result against the brute force: kind from rank(A) and rank([A|b]), rank, and for Unique and Many the equations and zeros at free columns.
bool brute_solve_ok(const Sys& s, const SolveOut& o) {
  const u32 rank = rank_minors(s.a, s.rows, s.cols, s.cols);
  std::vector<u32> ab(static_cast<std::size_t>(s.rows) * (s.cols + 1u));
  for (u32 i = 0; i < s.rows; ++i) {
    for (u32 j = 0; j < s.cols; ++j) ab[at(i, s.cols + 1u, j)] = s.a[at(i, s.cols, j)];
    ab[at(i, s.cols + 1u, s.cols)] = s.b[i];
  }
  const u32 rank_aug = rank_minors(ab, s.rows, s.cols + 1u, s.cols + 1u);
  if (o.rank != rank) return false;
  if (rank_aug > rank) return o.kind == SolveKind::Inconsistent;
  if (o.kind != (rank == s.cols ? SolveKind::Unique : SolveKind::Many)) return false;
  if (o.x.size() != s.cols) return false;
  if (mat_vec(s, o.x) != s.b) return false;
  u32 prev = 0;
  for (u32 j = 0; j < s.cols; ++j) {
    const u32 r = rank_minors(s.a, s.rows, s.cols, j + 1u);
    if (r == prev && o.x[j] != 0u) return false;  // not a pivot column: free variable must be 0
    prev = r;
  }
  return true;
}

u64 fold_solve(u64 h, const SolveOut& o) {
  h = fold_bytes(h, static_cast<u32>(o.kind), 1);
  h = fold_bytes(h, o.rank, 4);
  if (o.kind != SolveKind::Inconsistent) {
    for (std::size_t i = 0; i < o.x.size(); ++i) h = fold_bytes(h, o.x[i], 4);
  }
  return h;
}

struct Scratch {
  std::vector<u32> buf;
  u32 off;
  std::size_t words;
  u32* ptr() { return buf.data() + 4u + off; }
  bool intact() const {
    bool ok = true;
    for (u32 i = 0; i < 4u + off; ++i) ok = ok && buf[i] == kGuard;
    for (u32 i = 0; i < 4u; ++i) ok = ok && buf[4u + off + words + i] == kGuard;
    return ok;
  }
};

// Scratch of exactly `words` words at an odd (or zero) u32 offset, guard words on both sides, a varied garbage fill.
Scratch make_scratch(std::size_t words, u32 off, u32 fill) {
  Scratch s;
  s.off = off;
  s.words = words;
  s.buf.assign(words + 8u + off, kGuard);
  for (std::size_t i = 0; i < words; ++i) s.buf[4u + off + i] = fill + static_cast<u32>(static_cast<u64>(i) * 2654435761ull);
  return s;
}

struct DetOut {
  GaussResult res = GaussResult::NullArgument;
  u32 det = kSentinel;
  bool clean = false;
};

DetOut run_det(const std::vector<u32>& a, u32 n, u32 off, u32 fill) {
  const std::size_t cells = static_cast<std::size_t>(n) * n;
  Scratch sc = make_scratch(cells, off, fill);
  const std::vector<u32> a0 = a;
  DetOut o;
  o.res = gauss_det(a.data(), n, sc.ptr(), static_cast<u32>(cells), &o.det);
  o.clean = sc.intact() && a == a0;
  return o;
}

struct RankOut {
  GaussResult res = GaussResult::NullArgument;
  u32 rank = kSentinel;
  bool clean = false;
};

RankOut run_rank(const std::vector<u32>& a, u32 rows, u32 cols, u32 off, u32 fill) {
  const std::size_t cells = static_cast<std::size_t>(rows) * cols;
  Scratch sc = make_scratch(cells, off, fill);
  const std::vector<u32> a0 = a;
  RankOut o;
  o.res = gauss_rank(a.data(), rows, cols, sc.ptr(), static_cast<u32>(cells), &o.rank);
  o.clean = sc.intact() && a == a0;
  return o;
}

// Solve with scratch of exactly rows * (cols + 1) words and x followed by guard words.
SolveOut run_solve(const Sys& s, u32 off, u32 fill) {
  const std::size_t words = static_cast<std::size_t>(s.rows) * (static_cast<std::size_t>(s.cols) + 1u);
  Scratch sc = make_scratch(words, off, fill);
  std::vector<u32> xb(static_cast<std::size_t>(s.cols) + 4u, kSentinel);
  for (u32 i = 0; i < 4u; ++i) xb[static_cast<std::size_t>(s.cols) + i] = kGuard;
  const std::vector<u32> a0 = s.a;
  const std::vector<u32> b0 = s.b;
  SolveOut o;
  o.res = gauss_solve(s.a.data(), s.rows, s.cols, s.b.data(), sc.ptr(), static_cast<u32>(words), xb.data(), &o.rank, &o.kind);
  bool clean = sc.intact() && s.a == a0 && s.b == b0;
  for (u32 i = 0; i < 4u; ++i) clean = clean && xb[static_cast<std::size_t>(s.cols) + i] == kGuard;
  if (o.kind == SolveKind::Inconsistent || o.res != GaussResult::Ok) {
    for (u32 j = 0; j < s.cols; ++j) clean = clean && xb[j] == kSentinel;
  }
  o.clean = clean;
  o.x.assign(xb.begin(), xb.begin() + static_cast<std::ptrdiff_t>(s.cols));
  return o;
}

