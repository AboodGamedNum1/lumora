// One table case: rank, det (square only) and solve, against the digest and (small sizes) the brute force or the construction.
bool check_table_case(const Case& c, u32 salt) {
  Expect ex;
  Sys s;
  if (c.type == 0u) {
    s = gen_random(c.rows, c.cols, c.mode, c.bmode, c.seed);
  } else {
    s = gen_constructed(c.rows, c.cols, c.mode, c.bmode, c.perm, c.seed, &ex);
  }
  const SolveOut o = run_solve(s, salt % 2u, salt * 2654435761u);
  const RankOut r = run_rank(s.a, s.rows, s.cols, (salt + 1u) % 2u, salt * 40503u);
  bool ok = o.res == GaussResult::Ok && r.res == GaussResult::Ok && o.clean && r.clean && r.rank == o.rank;
  u64 h = fold_bytes(kFnvOff, r.rank, 4);
  u32 det = 0;
  if (is_square(s)) {
    const DetOut d = run_det(s.a, s.rows, salt % 3u == 0u ? 1u : 0u, salt * 7u);
    ok = ok && d.res == GaussResult::Ok && d.clean;
    det = d.det;
    h = fold_bytes(h, det, 4);
  }
  h = fold_solve(h, o);
  ok = ok && h == c.digest;
  if (o.kind != SolveKind::Inconsistent) ok = ok && mat_vec(s, o.x) == s.b;
  if (c.type == 1u) {
    ok = ok && o.rank == ex.rank && o.kind == ex.kind;
    if (is_square(s)) ok = ok && det == ex.det;
    if (ex.kind != SolveKind::Inconsistent) ok = ok && o.x == ex.x;
  } else if (c.rows <= 6u && c.cols <= 6u) {
    ok = ok && brute_solve_ok(s, o);
    if (is_square(s)) ok = ok && det == det_leibniz(s.a, s.rows);
    ok = ok && r.rank == rank_minors(s.a, s.rows, s.cols, s.cols);
  }
  return ok;
}

