// Nearest integer of num / den (den > 0), ties toward positive infinity. Written without the module's formula: floor of
// (2 * num + den) / (2 * den) by explicit adjustment of a truncated quotient.
i64 ref_round(i64 num, i64 den) {
  const i64 top = 2 * num + den, bot = 2 * den;
  i64 q = top / bot;
  while (q * bot > top) --q;
  while ((q + 1) * bot <= top) ++q;
  return q;
}
i64 ref_clamp(i64 v, i64 lo, i64 hi) { return v < lo ? lo : (v > hi ? hi : v); }

struct RFrac {
  i64 n, m;  // m > 0
};
bool rf_less(const RFrac& a, const RFrac& b) { return a.n * b.m < b.n * a.m; }

// Segment clip by candidate parameters: the visible interval ends at 0, 1 or a boundary crossing, so test those exactly.
bool ref_seg(const Rect& r, const Point& p0, const Point& p1, Point* a, Point* b) {
  const i64 dx = static_cast<i64>(p1.x) - p0.x, dy = static_cast<i64>(p1.y) - p0.y;
  std::vector<RFrac> cands{{0, 1}, {1, 1}};
  const auto add = [&](i64 c, i64 p, i64 d) {
    if (d == 0) return;
    RFrac f{c - p, d};
    if (f.m < 0) {
      f.n = -f.n;
      f.m = -f.m;
    }
    if (f.n >= 0 && f.n <= f.m) cands.push_back(f);
  };
  add(r.x0, p0.x, dx);
  add(r.x1, p0.x, dx);
  add(r.y0, p0.y, dy);
  add(r.y1, p0.y, dy);
  bool any = false;
  RFrac lo{0, 1}, hi{0, 1};
  for (const RFrac& f : cands) {
    const i64 X = static_cast<i64>(p0.x) * f.m + dx * f.n, Y = static_cast<i64>(p0.y) * f.m + dy * f.n;
    if (X < static_cast<i64>(r.x0) * f.m || X > static_cast<i64>(r.x1) * f.m) continue;
    if (Y < static_cast<i64>(r.y0) * f.m || Y > static_cast<i64>(r.y1) * f.m) continue;
    if (!any) {
      lo = hi = f;
      any = true;
    } else {
      if (rf_less(f, lo)) lo = f;
      if (rf_less(hi, f)) hi = f;
    }
  }
  if (!any) return false;
  const auto at = [&](const RFrac& f) {
    return Point{static_cast<std::int32_t>(ref_clamp(ref_round(static_cast<i64>(p0.x) * f.m + dx * f.n, f.m), r.x0, r.x1)),
                 static_cast<std::int32_t>(ref_clamp(ref_round(static_cast<i64>(p0.y) * f.m + dy * f.n, f.m), r.y0, r.y1))};
  };
  *a = at(lo);
  *b = at(hi);
  return true;
}

Point ref_cross(const Point& p, const Point& q, bool on_x, std::int32_t c) {
  const i64 pa = on_x ? p.x : p.y, qa = on_x ? q.x : q.y, po = on_x ? p.y : p.x, qo = on_x ? q.y : q.x;
  i64 den = qa - pa, num = po * den + (qo - po) * (c - pa);
  if (den < 0) {
    den = -den;
    num = -num;
  }
  const std::int32_t v = static_cast<std::int32_t>(ref_round(num, den));
  return on_x ? Point{c, v} : Point{v, c};
}
Pts ref_stage(const Pts& in, bool on_x, bool ge, std::int32_t c) {
  Pts out;
  const auto inside = [&](const Point& p) {
    const std::int32_t v = on_x ? p.x : p.y;
    return ge ? v >= c : v <= c;
  };
  for (std::size_t i = 0; i < in.size(); ++i) {
    const Point p = in[(i + in.size() - 1) % in.size()], q = in[i];
    const bool a = inside(p), b = inside(q);
    if (a && b) out.push_back(q);
    else if (a) out.push_back(ref_cross(p, q, on_x, c));
    else if (b) {
      out.push_back(ref_cross(p, q, on_x, c));
      out.push_back(q);
    }
  }
  return out;
}
Pts ref_poly(const Rect& r, Pts p, std::size_t* max_stage = nullptr) {
  std::size_t mx = p.size();
  p = ref_stage(p, true, true, r.x0);
  mx = std::max(mx, p.size());
  p = ref_stage(p, false, true, r.y0);
  mx = std::max(mx, p.size());
  p = ref_stage(p, true, false, r.x1);
  mx = std::max(mx, p.size());
  p = ref_stage(p, false, false, r.y1);
  mx = std::max(mx, p.size());
  if (max_stage != nullptr) *max_stage = mx;
  return p;
}
void ref_line(const Rect& r, const Pts& in, Pts& pts, std::vector<u32>& ends) {
  pts.clear();
  ends.clear();
  bool open = false;
  for (std::size_t i = 0; i + 1 < in.size(); ++i) {
    Point a{}, b{};
    if (!ref_seg(r, in[i], in[i + 1], &a, &b)) {
      if (open) ends.push_back(static_cast<u32>(pts.size()));
      open = false;
      continue;
    }
    if (open && pts.back() == a) {
      pts.push_back(b);
    } else {
      if (open) ends.push_back(static_cast<u32>(pts.size()));
      pts.push_back(a);
      pts.push_back(b);
      open = true;
    }
  }
  if (open) ends.push_back(static_cast<u32>(pts.size()));
}

