  REQUIRE(call({10, 0, 0, 10}, tri.data(), 0, out.data(), bound, scratch.data(), sneed, &cnt) == Status::BadCount);
  REQUIRE(call(A, tri.data(), 1, out.data(), bound, scratch.data(), sneed, &cnt) == Status::BadCount);
  REQUIRE(call(A, tri.data(), 2, out.data(), bound, scratch.data(), sneed, &cnt) == Status::BadCount);
