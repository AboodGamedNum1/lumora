  const u32 n = 3, bound = polygon_bound(n), sneed = scratch_size(n);
  Pts out(bound + 8, Point{kSentinelCoord, kSentinelCoord}), scratch(sneed + 8, Point{kSentinelCoord, kSentinelCoord});
  u32 cnt = kSentinelWord;
  const auto untouched = [&] {
    for (const Point& q : out) REQUIRE(q == Point{kSentinelCoord, kSentinelCoord});
    for (const Point& q : scratch) REQUIRE(q == Point{kSentinelCoord, kSentinelCoord});
    REQUIRE(cnt == kSentinelWord);
  };
  const auto call = [&](const Rect& r, const Point* in, u32 count, Point* o, u32 ocap, Point* sc, u32 scap, u32* oc) {
    return clip_polygon(r, in, count, o, ocap, sc, scap, oc);
  };
  // NullBuffer comes first, even with bad counts, rect and points
  REQUIRE(call(A, nullptr, n, out.data(), bound, scratch.data(), sneed, &cnt) == Status::NullBuffer);
  REQUIRE(call(A, tri.data(), n, nullptr, bound, scratch.data(), sneed, &cnt) == Status::NullBuffer);
  REQUIRE(call(A, tri.data(), n, out.data(), bound, nullptr, sneed, &cnt) == Status::NullBuffer);
  REQUIRE(call(A, tri.data(), n, out.data(), bound, scratch.data(), sneed, nullptr) == Status::NullBuffer);
  REQUIRE(call({10, 0, 0, 10}, nullptr, 2, out.data(), 0, scratch.data(), 0, &cnt) == Status::NullBuffer);
  REQUIRE(call(A, tri.data(), n, nullptr, 0, scratch.data(), sneed, &cnt) == Status::NullBuffer);  // required even at capacity 0
  REQUIRE(call(A, tri.data(), n, out.data(), bound, nullptr, 0, &cnt) == Status::NullBuffer);
  untouched();
