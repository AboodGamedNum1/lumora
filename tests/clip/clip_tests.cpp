struct PolyRun {
  Status st = Status::Ok;
  Pts out;
  u32 count = 0;
};
PolyRun run_poly(const Rect& r, const Pts& in) {
  PolyRun run;
  const u32 n = static_cast<u32>(in.size());
  Pts out(polygon_bound(n), Point{kSentinelCoord, kSentinelCoord});
  Pts scratch(scratch_size(n), Point{kSentinelCoord, kSentinelCoord});
  u32 cnt = kSentinelWord;
  run.st = clip_polygon(r, in.data(), n, out.data(), static_cast<u32>(out.size()), scratch.data(), static_cast<u32>(scratch.size()), &cnt);
  run.count = cnt;
  if (run.st == Status::Ok) run.out.assign(out.begin(), out.begin() + cnt);
  return run;
}

struct LineRun {
  Status st = Status::Ok;
  Pts pts;
  std::vector<u32> ends;
};
LineRun run_line(const Rect& r, const Pts& in) {
  LineRun run;
  const u32 n = static_cast<u32>(in.size());
  Pts pts(2 * (n - 1), Point{kSentinelCoord, kSentinelCoord});
  std::vector<u32> ends(n - 1, kSentinelWord);
  u32 pc = kSentinelWord, op = kSentinelWord;
  run.st = clip_polyline(r, in.data(), n, pts.data(), static_cast<u32>(pts.size()), ends.data(), static_cast<u32>(ends.size()), &pc, &op);
  if (run.st == Status::Ok) {
    run.pts.assign(pts.begin(), pts.begin() + op);
    run.ends.assign(ends.begin(), ends.begin() + pc);
  }
  return run;
}

Rect rand_rect(Lcg& l, std::int32_t R) {
  const std::int32_t ax = l.rng(-R, R), bx = l.rng(-R, R), ay = l.rng(-R, R), by = l.rng(-R, R);
  return {std::min(ax, bx), std::min(ay, by), std::max(ax, bx), std::max(ay, by)};
}
std::int32_t rand_range2(std::int32_t R) { return static_cast<std::int32_t>(std::min<i64>(kK, static_cast<i64>(R) + R / 2)); }

