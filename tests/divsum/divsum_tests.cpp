// The quotient-block route: every k in [k, hi] has the same floor(n / k) = q.
u64 block_d(u64 n) {
  u64 s = 0;
  for (u64 k = 1; k <= n;) {
    const u64 q = n / k;
    const u64 hi = n / q;
    s += q * (hi - k + 1u);
    k = hi + 1u;
  }
  return s;
}
u64 block_s(u64 n) {
  u64 s = 0;
  for (u64 k = 1; k <= n;) {
    const u64 q = n / k;
    const u64 hi = n / q;
    s += q * (tri(hi) - tri(k - 1u));
    k = hi + 1u;
  }
  return s;
}
// d(n) and sigma(n) by trial division.
u64 d_of(u64 n) {
  u64 r = 1;
  u64 rem = n;
  for (u64 q = 2; q * q <= rem; ++q) {
    if (rem % q != 0u) continue;
    u64 e = 0;
    while (rem % q == 0u) {
      rem /= q;
      ++e;
    }
    r *= e + 1u;
  }
  if (rem > 1u) r *= 2u;
  return r;
}
u64 sigma_of(u64 n) {
  u64 r = 1;
  u64 rem = n;
  for (u64 q = 2; q * q <= rem; ++q) {
    if (rem % q != 0u) continue;
    u64 term = 1;
    u64 pw = 1;
    while (rem % q == 0u) {
      rem /= q;
      pw *= q;
      term += pw;
    }
    r *= term;
  }
  if (rem > 1u) r *= rem + 1u;
  return r;
}

struct Sieve {
  std::vector<u64> D;  // prefix sums of d(k)
  std::vector<u64> S;  // prefix sums of sigma(k)
};
const Sieve& sieve() {
  static const Sieve s = [] {
    std::vector<u32> dd(kTop + 1u, 0u);
    std::vector<u64> sg(kTop + 1u, 0u);
    for (u32 d = 1; d <= kTop; ++d)
      for (u32 m = d; m <= kTop; m += d) {
        ++dd[m];
        sg[m] += d;
      }
    Sieve r;
    r.D.assign(kTop + 1u, 0u);
    r.S.assign(kTop + 1u, 0u);
    for (u32 k = 1; k <= kTop; ++k) {
      r.D[k] = r.D[k - 1u] + dd[k];
      r.S[k] = r.S[k - 1u] + sg[k];
    }
    return r;
  }();
  return s;
}

