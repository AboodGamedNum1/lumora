const u32 kSentinel = 0xDEADBEEFu;
const u32 kGuard = 0xC0FFEE11u;
const u64 kFnvOff = 0xCBF29CE484222325ull;
const u64 kFnvPrime = 0x100000001B3ull;
const u32 kFlagSq = 1u;
const u32 kFlagAlias = 2u;

u64 fold_bytes(u64 h, u64 v, int nbytes) {
  for (int i = 0; i < nbytes; ++i) {
    h ^= (v & 0xFFu);
    v >>= 8;
    h *= kFnvPrime;
  }
  return h;
}

u64 digest_out(u64 h, const std::vector<u32>& out) {
  h = fold_bytes(h, out.size(), 4);
  for (std::size_t i = 0; i < out.size(); ++i) h = fold_bytes(h, out[i], 4);
  return h;
}

struct Lcg {
  u64 s;
  u64 rnd(u64 k) {
    s = s * 6364136223846793005ull + 1442695040888963407ull;
    return (s >> 33) % k;
  }
};

u32 entry(Lcg& g, u32 mode) {
  switch (mode) {
    case 0: return static_cast<u32>(g.rnd(kMod));
    case 1: return kMod - 1u - static_cast<u32>(g.rnd(4));
    case 2: return static_cast<u32>(g.rnd(3));
    case 3: return g.rnd(5) == 0 ? static_cast<u32>(g.rnd(kMod)) : 0u;
    case 4: return kMod - 1u;
    default: return 0u;
  }
}

struct Pair {
  std::vector<u32> a;
  std::vector<u32> b;
};

Pair gen(u32 na, u32 nb, u32 mode, u64 seed, bool sq) {
  Lcg g{seed};
  Pair p;
  for (u32 i = 0; i < na; ++i) p.a.push_back(entry(g, mode));
  if (sq) {
    p.b = p.a;
  } else {
    for (u32 i = 0; i < nb; ++i) p.b.push_back(entry(g, mode));
  }
  return p;
}

// In-test schoolbook: the defining double sum.
std::vector<u32> school(const std::vector<u32>& a, const std::vector<u32>& b) {
  std::vector<u32> out;
  if (a.empty() || b.empty()) return out;
  out.assign(a.size() + b.size() - 1, 0u);
  for (std::size_t i = 0; i < a.size(); ++i) {
    for (std::size_t j = 0; j < b.size(); ++j) {
      const u64 prod = (static_cast<u64>(a[i]) * b[j]) % kMod;
      out[i + j] = static_cast<u32>((static_cast<u64>(out[i + j]) + prod) % kMod);
    }
  }
  return out;
}

// m for r >= 1, by the definition: smallest power of two at least r.
u32 pad_of(u64 r) {
  u32 m = 1;
  while (m < r) m *= 2u;
  return m;
}

u64 rlen(u32 na, u32 nb) { return (na == 0 || nb == 0) ? 0ull : static_cast<u64>(na) + nb - 1ull; }

struct Run {
  NttResult res = NttResult::NullArgument;
  u32 len = kSentinel;
  std::vector<u32> out;
  bool clean = false;  // guards intact, extra capacity untouched, inputs unchanged
};

// Separate arrays, exact scratch (2m words, odd offset, guard words either side), out_cap = r + extra with guard words after it.
Run run_sep(const std::vector<u32>& a, const std::vector<u32>& b, u32 extra, u32 fill, u32 off) {
  const u32 na = static_cast<u32>(a.size());
  const u32 nb = static_cast<u32>(b.size());
  const u64 r = rlen(na, nb);
  const u32 m = r == 0 ? 0u : pad_of(r);
  const std::size_t sw = static_cast<std::size_t>(m) * 2u;
  std::vector<u32> sb(sw + 8u + off, fill);
  for (u32 i = 0; i < 4u + off; ++i) sb[i] = kGuard;
  for (u32 i = 0; i < 4u; ++i) sb[4u + off + sw + i] = kGuard;
  for (std::size_t i = 0; i < sw; ++i) sb[4u + off + i] = fill + static_cast<u32>(static_cast<u64>(i) * 2654435761ull);
  std::vector<u32> ob(static_cast<std::size_t>(r) + extra + 4u, kSentinel);
  for (u32 i = 0; i < 4u; ++i) ob[static_cast<std::size_t>(r) + extra + i] = kGuard;
  const std::vector<u32> a0 = a;
  const std::vector<u32> b0 = b;
  Run run;
  u32 len = kSentinel;
  run.res = ntt_convolve(a.data(), na, b.data(), nb, sb.data() + 4u + off, static_cast<u32>(sw), ob.data(), static_cast<u32>(r) + extra, &len);
  run.len = len;
  bool clean = (a == a0) && (b == b0);
  for (u32 i = 0; i < 4u + off; ++i) clean = clean && sb[i] == kGuard;
  for (u32 i = 0; i < 4u; ++i) clean = clean && sb[4u + off + sw + i] == kGuard;
  for (u32 i = 0; i < 4u; ++i) clean = clean && ob[static_cast<std::size_t>(r) + extra + i] == kGuard;
  for (u32 i = 0; i < extra; ++i) clean = clean && ob[static_cast<std::size_t>(r) + i] == kSentinel;
  run.clean = clean;
  run.out.assign(ob.begin(), ob.begin() + static_cast<std::ptrdiff_t>(r));
  return run;
}

// Equal-pointer aliasing. kind 1: a == out; 2: b == out; 3: a == b (b is a prefix of a, or a of b); 4: a == b == out. out_cap is exactly r.
// Both arrays are the given vectors; for kinds 3 and 4 the shorter one must be a prefix of the longer one.
std::vector<u32> run_alias(int kind, const std::vector<u32>& a, const std::vector<u32>& b, NttResult* res) {
  const u32 na = static_cast<u32>(a.size());
  const u32 nb = static_cast<u32>(b.size());
  const u64 r = rlen(na, nb);
  const u32 m = pad_of(r);
  std::vector<u32> scratch(static_cast<std::size_t>(m) * 2u, 0x5A5A5A5Au);
  std::vector<u32> buf(static_cast<std::size_t>(r), kSentinel);
  std::vector<u32> other;
  u32 len = kSentinel;
  const u32 cap = static_cast<u32>(r);
  if (kind == 1) {
    for (u32 i = 0; i < na; ++i) buf[i] = a[i];
    other = b;
    *res = ntt_convolve(buf.data(), na, other.data(), nb, scratch.data(), 2u * m, buf.data(), cap, &len);
  } else if (kind == 2) {
    for (u32 i = 0; i < nb; ++i) buf[i] = b[i];
    other = a;
    *res = ntt_convolve(other.data(), na, buf.data(), nb, scratch.data(), 2u * m, buf.data(), cap, &len);
  } else {
    const std::vector<u32>& longer = na >= nb ? a : b;
    other = longer;
    if (kind == 3) {
      *res = ntt_convolve(other.data(), na, other.data(), nb, scratch.data(), 2u * m, buf.data(), cap, &len);
    } else {
      for (std::size_t i = 0; i < longer.size(); ++i) buf[i] = longer[i];
      *res = ntt_convolve(buf.data(), na, buf.data(), nb, scratch.data(), 2u * m, buf.data(), cap, &len);
    }
  }
  if (len != r) *res = NttResult::TooLarge;
  return buf;
}

