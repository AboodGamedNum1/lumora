#!/usr/bin/env python3
"""Independent reference for core/zorder tests.

Morton codes are built bit by bit with a plain loop (bit i of x goes to bit 2i, and so on), not with mask tricks. The Hilbert curve is
built from its geometric definition: the curve of order k has four quadrants in the order (0,0), (0,1), (1,1), (1,0) (x first); quadrant 0
holds the order k-1 curve with x and y swapped, quadrants 1 and 2 hold it unchanged, quadrant 3 holds it mirrored along the anti-diagonal.
Order 1 is the four cells in that order. No bit-twiddling routine is used. The script prints a C++ include: sample tables and digests.
"""
import sys

M64 = (1 << 64) - 1
FNV_OFF = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
MASK = (1 << 32) - 1


class Lcg:
    def __init__(self, seed):
        self.s = seed & MASK

    def next(self):
        self.s = (self.s * 1664525 + 1013904223) & MASK
        return self.s >> 8


def fnv(h, v):
    for k in range(4):
        h ^= (v >> (8 * k)) & 255
        h = (h * FNV_PRIME) & M64
    return h


def morton2(x, y):
    code = 0
    for i in range(16):
        code |= ((x >> i) & 1) << (2 * i)
        code |= ((y >> i) & 1) << (2 * i + 1)
    return code


def morton3(x, y, z):
    code = 0
    for i in range(10):
        code |= ((x >> i) & 1) << (3 * i)
        code |= ((y >> i) & 1) << (3 * i + 1)
        code |= ((z >> i) & 1) << (3 * i + 2)
    return code


def hilbert_cell(order, d):
    """Cell (x, y) at distance d on the curve of the given order, by the geometric recursion."""
    if order == 1:
        return [(0, 0), (0, 1), (1, 1), (1, 0)][d]
    s = 1 << (order - 1)
    q, rest = divmod(d, s * s)
    x, y = hilbert_cell(order - 1, rest)
    if q == 0:
        return (y, x)
    if q == 1:
        return (x, y + s)
    if q == 2:
        return (x + s, y + s)
    return (2 * s - 1 - y, s - 1 - x)


def main():
    out = ["// Generated by tools/zorder_ref.py. Do not edit."]

    def arr(name, typ, vals):
        out.append("static const %s %s[] = {%s};" % (typ, name, ",".join(str(v) for v in vals)))

    r = Lcg(2024)
    # Morton 2D samples: corners, single bits, random
    pts2 = [(0, 0), (65535, 65535), (65535, 0), (0, 65535), (1, 0), (0, 1), (255, 256), (256, 255), (43690, 21845), (21845, 43690)]
    for i in range(16):
        pts2.append((1 << i, 0))
        pts2.append((0, 1 << i))
    for _ in range(1500):
        pts2.append((r.next() & 0xFFFF, r.next() & 0xFFFF))
    flat = []
    for x, y in pts2:
        flat += [x, y, morton2(x, y)]
    arr("kM2", "std::uint32_t", flat)
    # Morton 3D samples
    pts3 = [(0, 0, 0), (1023, 1023, 1023), (1023, 0, 0), (0, 1023, 0), (0, 0, 1023), (512, 0, 1), (341, 682, 341)]
    for i in range(10):
        pts3 += [(1 << i, 0, 0), (0, 1 << i, 0), (0, 0, 1 << i)]
    for _ in range(1500):
        pts3.append((r.next() & 1023, r.next() & 1023, r.next() & 1023))
    flat = []
    for x, y, z in pts3:
        flat += [x, y, z, morton3(x, y, z)]
    arr("kM3", "std::uint32_t", flat)
    # digests: Morton 2D over 0..255 squared (row by row), Morton 3D over 0..15 cubed
    h = FNV_OFF
    for y in range(256):
        for x in range(256):
            h = fnv(h, morton2(x, y))
    out.append("static const std::uint64_t kM2Digest = %dull;" % h)
    h = FNV_OFF
    for z in range(16):
        for y in range(16):
            for x in range(16):
                h = fnv(h, morton3(x, y, z))
    out.append("static const std::uint64_t kM3Digest = %dull;" % h)
    # Hilbert: full tables for orders 1..4, random and boundary samples for orders 5..16
    hs = []
    for order in range(1, 5):
        for d in range(4 ** order):
            x, y = hilbert_cell(order, d)
            hs += [order, d, x, y]
    for order in range(5, 17):
        total = 4 ** order
        ds = [0, 1, 2, 3, total - 1, total - 2, total // 4 - 1, total // 4, total // 2 - 1, total // 2, 3 * total // 4 - 1, 3 * total // 4]
        for _ in range(120):
            ds.append(((r.next() << 12) ^ r.next()) % total)
        for d in ds:
            x, y = hilbert_cell(order, d)
            hs += [order, d, x, y]
    arr("kH", "std::uint32_t", hs)
    # digests of the whole curve for orders 1..8
    digs = []
    for order in range(1, 9):
        h = FNV_OFF
        for d in range(4 ** order):
            x, y = hilbert_cell(order, d)
            h = fnv(h, x)
            h = fnv(h, y)
        digs.append("%dull" % h)
    out.append("static const std::uint64_t kHDigest[8] = {%s};" % ",".join(digs))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
