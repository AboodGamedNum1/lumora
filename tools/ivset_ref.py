#!/usr/bin/env python3
"""Independent reference for core/ivset tests.

The model is a plain Python set of integers. An insert adds the integers lo .. hi-1, a remove discards them, and the canonical interval
list is rebuilt from the sorted members after every operation (consecutive integers form one interval, so touching intervals merge by
construction). A result is Full when the rebuilt list would be longer than the capacity; the state then stays as it was. The script
prints a C++ include with the scenarios and the expected results, and a digest for one larger scenario. The test file has no
hand-typed expected values.
"""
import sys

MASK = (1 << 32) - 1
FNV_OFF = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
M64 = (1 << 64) - 1


class Lcg:
    def __init__(self, seed):
        self.s = seed & MASK

    def next(self):
        self.s = (self.s * 1664525 + 1013904223) & MASK
        return self.s >> 8


def intervals(members):
    out = []
    for v in sorted(members):
        if out and out[-1][1] == v:
            out[-1][1] = v + 1
        else:
            out.append([v, v + 1])
    return out


def apply(state, kind, lo, hi, capacity):
    """Returns (result, new_state). result 0 = Ok, 5 = Full."""
    new = set(state)
    rng = range(lo, hi)
    if kind == 0:
        new.update(rng)
    else:
        new.difference_update(rng)
    if len(intervals(new)) > capacity:
        return 5, state
    return 0, new


def make_ops(r, count, universe, max_len):
    ops = []
    for _ in range(count):
        kind = r.next() % 2
        lo = r.next() % (universe + 1)
        mode = r.next() % 6
        if mode == 0:
            hi = lo
        else:
            hi = min(universe, lo + r.next() % (max_len + 1))
        ops.append((kind, lo, hi))
    return ops


def fnv(h, v):
    for k in range(4):
        h ^= (v >> (8 * k)) & 255
        h = (h * FNV_PRIME) & M64
    return h


def main():
    base_list = [0, 1000, MASK - 63]
    caps = [1, 2, 4, 64]
    scen = []
    seed = 11
    for base in base_list:
        for cap in caps:
            for mx in (3, 12, 63):
                r = Lcg(seed)
                seed += 1
                ops = make_ops(r, 220, 63, mx)
                scen.append((base, cap, ops))
    rows, OPS, RES, CNT, MASKS, STOFF, STATE = [], [], [], [], [], [], []
    for base, cap, ops in scen:
        state = set()
        rows.append((base, cap, len(ops), len(OPS)))
        for kind, lo, hi in ops:
            res, state = apply(state, kind, lo, hi, cap)
            iv = intervals(state)
            OPS.append((kind, lo, hi))
            RES.append(res)
            CNT.append(len(iv))
            m = 0
            for v in state:
                m |= 1 << v
            MASKS.append(m)
            STOFF.append(len(STATE))
            for a, b in iv:
                STATE.append((a, b))
    # larger scenario for the golden digest: 3000 operations over 2000 positions, capacity 25, base 70000
    r = Lcg(987654321)
    ops = make_ops(r, 3000, 2000, 12)
    state = set()
    h = FNV_OFF
    full = 0
    for kind, lo, hi in ops:
        res, state = apply(state, kind, lo, hi, 25)
        full += res == 5
        iv = intervals(state)
        h = fnv(h, res)
        h = fnv(h, len(iv))
        for a, b in iv:
            h = fnv(h, 70000 + a)
            h = fnv(h, 70000 + b)
    out = ["// Generated by tools/ivset_ref.py. Do not edit."]
    out.append("struct Scenario { std::uint32_t base, capacity, nops, op_off; };")
    out.append("static const Scenario kScenarios[] = {%s};" % ",".join("{%du,%d,%d,%d}" % r for r in rows))
    out.append("static const std::uint32_t kNumScenarios = %d;" % len(rows))

    def arr(name, typ, vals):
        out.append("static const %s %s[] = {%s};" % (typ, name, ",".join(str(v) for v in vals)))

    arr("kOpKind", "std::uint32_t", [o[0] for o in OPS])
    arr("kOpLo", "std::uint32_t", [o[1] for o in OPS])
    arr("kOpHi", "std::uint32_t", [o[2] for o in OPS])
    arr("kRes", "std::uint32_t", RES)
    arr("kCnt", "std::uint32_t", CNT)
    arr("kMask", "std::uint64_t", ["%dull" % m for m in MASKS])
    arr("kStateOff", "std::uint32_t", STOFF)
    arr("kStateLo", "std::uint32_t", [a for a, b in STATE])
    arr("kStateHi", "std::uint32_t", [b for a, b in STATE])
    out.append("static const std::uint64_t kBigDigest = %dull;" % h)
    out.append("static const std::uint32_t kBigFull = %d;" % full)
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
