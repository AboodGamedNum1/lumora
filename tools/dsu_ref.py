#!/usr/bin/env python3
"""Independent reference for core/dsu tests.

It does not use a parent array or path compression. Sets are kept as an explicit label per element (quick-find): merging relabels
every member of one set. The canonical root of a set is the minimum of its members, taken by scanning. The script prints a C++ include
with the operation lists and the expected results; the test file holds no hand-typed expected numbers.
"""
import sys

MASK = (1 << 32) - 1


class Lcg:
    def __init__(self, seed):
        self.s = seed & MASK

    def next(self):
        self.s = (self.s * 1664525 + 1013904223) & MASK
        return self.s >> 8


def make_ops(n, mode, count, seed):
    r = Lcg(seed)
    ops = []
    for i in range(count):
        if mode == "random":
            a, b = r.next() % n, r.next() % n
        elif mode == "chain_up":
            a, b = i % (n - 1), i % (n - 1) + 1
        elif mode == "chain_down":
            j = (n - 2) - (i % (n - 1))
            a, b = j + 1, j
        elif mode == "star":
            a, b = 0, 1 + i % (n - 1)
        elif mode == "star_high":
            a, b = n - 1, i % (n - 1)
        elif mode == "same":
            a = r.next() % n
            b = a
        elif mode == "repeat":
            a, b = (r.next() % n) if i % 3 == 0 else ops[-1][0], r.next() % n if i % 3 == 0 else ops[-1][1]
        else:
            raise ValueError(mode)
        ops.append((a, b))
    return ops


def simulate(n, ops):
    label = list(range(n))
    merged, counts, finds = [], [], []
    for a, b in ops:
        la, lb = label[a], label[b]
        if la == lb:
            merged.append(0)
        else:
            for i in range(n):
                if label[i] == lb:
                    label[i] = la
            merged.append(1)
        counts.append(len(set(label)))
        q = (a * 7 + b) % n
        finds.append(min(i for i in range(n) if label[i] == label[q]))
    roots = [min(i for i in range(n) if label[i] == label[x]) for x in range(n)]
    return merged, counts, finds, roots


SIZES = [(2, 20), (3, 20), (5, 40), (16, 80), (64, 200), (257, 600), (1000, 1500)]
MODES = ["random", "chain_up", "chain_down", "star", "star_high", "same", "repeat"]


def main():
    scen = []
    seed = 1
    for n, cnt in SIZES:
        for m in MODES:
            ops = make_ops(n, m, cnt, seed)
            seed += 1
            merged, counts, finds, roots = simulate(n, ops)
            scen.append((n, ops, merged, counts, finds, roots))
    out = []
    A, B, MG, CT, FD, RT = [], [], [], [], [], []
    rows = []
    for n, ops, merged, counts, finds, roots in scen:
        rows.append((n, len(ops), len(A), len(RT)))
        for (a, b), mg, ct, fd in zip(ops, merged, counts, finds):
            A.append(a); B.append(b); MG.append(mg); CT.append(ct); FD.append(fd)
        RT.extend(roots)

    def arr(name, vals):
        out.append("static const std::uint32_t %s[] = {%s};" % (name, ",".join(str(v) for v in vals)))

    out.append("// Generated by tools/dsu_ref.py. Do not edit.")
    out.append("struct Scenario { std::uint32_t n, nops, op_off, root_off; };")
    out.append("static const Scenario kScenarios[] = {%s};" % ",".join("{%d,%d,%d,%d}" % r for r in rows))
    out.append("static const std::uint32_t kNumScenarios = %d;" % len(rows))
    arr("kOpA", A); arr("kOpB", B); arr("kMerged", MG); arr("kCount", CT); arr("kFind", FD); arr("kRoots", RT)
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
