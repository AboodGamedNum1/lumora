#!/usr/bin/env python3
"""Independent reference for core/bytesearch tests.

The small scenarios use explicit Python loops over slices (list every occurrence position, then take the first, the last, and a greedy
left-to-right count). They are cross-checked here against the Python bytes methods. The case-insensitive comparison folds with an
explicit table for A-Z only. The script prints a C++ include with the byte pool, the scenario tables, and a digest for one larger run.
"""
import sys

M64 = (1 << 64) - 1
FNV_OFF = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
MASK = (1 << 32) - 1


class Lcg:
    def __init__(self, seed):
        self.s = seed & MASK

    def next(self):
        self.s = (self.s * 1664525 + 1013904223) & MASK
        return self.s >> 8


def fnv(h, v):
    for k in range(4):
        h ^= (v >> (8 * k)) & 255
        h = (h * FNV_PRIME) & M64
    return h


def positions(hay, needle):
    out = []
    for p in range(0, len(hay) - len(needle) + 1):
        if hay[p:p + len(needle)] == needle:
            out.append(p)
    return out


def greedy_count(hay, needle):
    count = 0
    p = 0
    while p + len(needle) <= len(hay):
        if hay[p:p + len(needle)] == needle:
            count += 1
            p += len(needle)
        else:
            p += 1
    return count


FOLD = bytes((c + 32) if 65 <= c <= 90 else c for c in range(256))


def fold_equal(a, b):
    if len(a) != len(b):
        return False
    return all(FOLD[x] == FOLD[y] for x, y in zip(a, b))


def expect(hay, needle):
    ps = positions(hay, needle)
    f = (1, ps[0]) if ps else (0, 0)
    l = (1, ps[-1]) if ps else (0, 0)
    if len(needle) == 0:
        # empty needle: found at 0 for find, at len(hay) for find_last; count is an error
        assert ps == list(range(len(hay) + 1))
        return f, l, 0
    assert hay.find(needle) == (ps[0] if ps else -1)
    assert hay.rfind(needle) == (ps[-1] if ps else -1)
    cnt = greedy_count(hay, needle)
    assert cnt == hay.count(needle)
    return f, l, cnt


def main():
    r = Lcg(31415)
    alpha = [97, 98, 65, 66, 0, 255, 128, 64, 91]
    pool = bytearray()
    rows = []

    def add(b):
        off = len(pool)
        pool.extend(b)
        return off

    for i in range(3000):
        nh = r.next() % 41
        nn = r.next() % 7
        k = 2 + (i % 3)
        hay = bytes(alpha[r.next() % k] for _ in range(nh))
        if i % 4 == 0 and nh > 0 and nn <= nh:
            s = r.next() % (nh - nn + 1)
            needle = hay[s:s + nn]
        else:
            needle = bytes(alpha[r.next() % k] for _ in range(nn))
        f, l, cnt = expect(hay, needle)
        rows.append((add(hay), nh, add(needle), nn, f[0], f[1], l[0], l[1], cnt))
    out = ["// Generated by tools/bytesearch_ref.py. Do not edit."]
    out.append("static const std::uint32_t kRows[] = {%s};" % ",".join(str(v) for row in rows for v in row))
    out.append("static const std::uint32_t kNumRows = %d;" % len(rows))
    # case-insensitive pairs
    crow = []
    for i in range(2000):
        n = r.next() % 20
        a = bytes(r.next() % 256 if i % 5 == 0 else alpha[r.next() % 9] if i % 2 else 65 + r.next() % 60 for _ in range(n))
        b = bytearray(a)
        for j in range(n):
            if r.next() % 2 and (65 <= b[j] <= 90 or 97 <= b[j] <= 122):
                b[j] ^= 32
        mode = r.next() % 5
        if mode == 0 and n > 0:
            b[r.next() % n] = r.next() % 256
        elif mode == 1:
            b = b + bytes([97])
        elif mode == 2 and n > 0:
            b = b[:-1]
        b = bytes(b)
        crow.extend([add(a), len(a), add(b), len(b), 1 if fold_equal(a, b) else 0])
    out.insert(1, "static const std::uint8_t kPool[] = {%s};" % ",".join(str(b) for b in pool))
    out.append("static const std::uint32_t kCRows[] = {%s};" % ",".join(str(v) for v in crow))
    out.append("static const std::uint32_t kNumCRows = %d;" % (len(crow) // 5))
    # larger run for the digest: 100000 bytes over 'a'..'c', 200 needles of length 1..12
    r = Lcg(271828)
    hay = bytes(97 + r.next() % 3 for _ in range(100000))
    h = FNV_OFF
    for _ in range(200):
        n = 1 + r.next() % 12
        needle = bytes(97 + r.next() % 3 for _ in range(n))
        f = hay.find(needle)
        l = hay.rfind(needle)
        c = hay.count(needle)
        h = fnv(h, 1 if f >= 0 else 0)
        h = fnv(h, f if f >= 0 else 0)
        h = fnv(h, 1 if l >= 0 else 0)
        h = fnv(h, l if l >= 0 else 0)
        h = fnv(h, c)
    out.append("static const std::uint64_t kBigDigest = %dull;" % h)
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
